'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const cp=require('node:child_process');
const source=path.join(__dirname,'../scripts/atualizar-vps-ssh.mjs');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'bq-ssh-update-test-'));
const live=path.join(tmp,'live'), upstream=path.join(tmp,'source');
const put=(base,p,value)=>{const target=path.join(base,p);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,value);};
const read=p=>fs.readFileSync(path.join(live,p),'utf8');
const run=(...args)=>cp.execFileSync(process.execPath,[source,...args],{cwd:live,encoding:'utf8'});
try {
    put(live,'app.js','globalThis.version = 1;');
    put(live,'package.json','{"name":"old"}');
    put(live,'client/index.html','old homepage');
    put(live,'client/js/main.js','var version = 1;');
    put(live,'client/maps/world_client.json','CUSTOM PUBLISHED MAP');
    put(live,'var/config/private.json','{"secret":true}');
    put(live,'.env','SECRET=private');
    put(upstream,'app.js','globalThis.version = 2;');
    put(upstream,'package.json','{"name":"new"}');
    put(upstream,'package-lock.json','{"lockfileVersion":3}');
    put(upstream,'client/index.html','new homepage');
    put(upstream,'client/js/main.js','var version = 2;');
    put(upstream,'client/css/controls.css','canvas { image-rendering: pixelated; }');
    put(upstream,'server/admin/public/updates.html','new admin updates page');
    put(upstream,'client/maps/world_client.json','SHOULD NOT OVERWRITE');
    put(upstream,'var/config/private.json','SHOULD NOT OVERWRITE');
    put(upstream,'.env','SHOULD NOT OVERWRITE');
    const archive=path.join(tmp,'snapshot.zip');
    cp.execFileSync('zip',['-qr',archive,'source'],{cwd:tmp});
    const preview=run('--check','--archive',archive);
    assert.match(preview,/Arquivos diferentes: 7/);
    assert.equal(read('client/index.html'),'old homepage');
    const result=run('--apply','--archive',archive);
    assert.match(result,/Código aplicado/);
    assert.equal(read('client/index.html'),'new homepage');
    assert.equal(read('package.json'),'{"name":"new"}');
    assert.equal(read('client/js/main.js'),'var version = 2;');
    assert.equal(read('client/maps/world_client.json'),'CUSTOM PUBLISHED MAP');
    assert.equal(read('.env'),'SECRET=private');
    assert.equal(read('var/config/private.json'),'{"secret":true}');
    const folder=path.join(live,'var/ssh-update-backups');
    const saved=fs.readdirSync(folder).map(n=>path.join(folder,n));
    assert.equal(saved.length,1);
    assert.equal(fs.readFileSync(path.join(saved[0],'app.js'),'utf8'),'globalThis.version = 1;');
    assert.equal(JSON.parse(fs.readFileSync(path.join(saved[0],'manifest.json'))).changed.length,7);
    assert.match(run('--check','--archive',archive),/Arquivos diferentes: 0/);
    // Invalid upstream JS must fail safely before touching production files.
    put(upstream,'client/js/main.js','const = broken;');
    cp.execFileSync('zip',['-q',archive,'source/client/js/main.js'],{cwd:tmp});
    assert.throws(()=>run('--apply','--archive',archive),/Command failed/);
    assert.equal(read('client/js/main.js'),'var version = 2;');
    console.log('SSH updater: dry-run, atomic apply, backups, private files, idempotence and JS syntax checks passed.');
} finally { fs.rmSync(tmp,{recursive:true,force:true}); }
